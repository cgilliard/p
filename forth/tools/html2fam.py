#!/usr/bin/env python3
"""html2fam -- a file's bytes as a fam word ( -- a n ): the web wallet's page
(web/wallet.html) for src/web.fam to serve.

Usage: html2fam.py FILE NAME > src/page.fam

The word pushes the bytes' address (auipc), jumps over them, and pushes
their length -- the bytes sit in the code, padded to whole words.  Run it
again whenever the page changes (src/page.fam is generated: don't edit it).
"""

import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, name = sys.argv[1], sys.argv[2]
    data = open(path, "rb").read()
    if len(name) > 8:
        sys.exit("html2fam: names are at most 8 characters")
    padded = data + bytes(-len(data) % 4)
    off = len(padded) + 4
    if off >= 1 << 20:
        sys.exit("html2fam: over 1 MiB")
    jal = 0x6F | ((off >> 1) & 0x3FF) << 21 | ((off >> 11) & 1) << 20 | ((off >> 12) & 0xFF) << 12
    out = [
        f"\\ {name} ( -- a n ) -- generated by tools/html2fam.py from {path}",
        f"\\ ({len(data)} bytes): don't edit; run it again when the file changes.",
        f": {name} ( -- a n )",
        "97020000 ,   \\ auipc t0,0",
        "93824201 ,   \\ addi t0,t0,20: the bytes, after this and the jal",
        "1301C1FF ,   \\ addi sp,sp,-4",
        "23205100 ,   \\ sw t0,0(sp)",
        f"{jal.to_bytes(4, 'little').hex().upper()} ,   \\ jal x0, past the bytes",
    ]
    for i in range(0, len(padded), 4):
        out.append(f"{padded[i:i + 4].hex().upper()} ,")
    out.append(f"{len(data):X} lit")
    out.append(";")
    print("\n".join(out))


if __name__ == "__main__":
    main()
